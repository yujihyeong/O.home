/** 글에서 맞춤법 의심 표현을 찾는다 — base는 위치 보정값(노드 시작 위치 등) */
export function findSpelling(text: string, base = 0): SpellIssue[] {
  const out: SpellIssue[] = [];
  for (const r of RULES) {
    r.re.lastIndex = 0;
    let m: RegExpExecArray | null;
    while ((m = r.re.exec(text))) {
      if (m[0] === '') { r.re.lastIndex++; continue; }
      const fix = typeof r.fix === 'string' ? r.fix : r.fix(m);
      if (fix === null || fix === m[0]) continue;
      out.push({ id: '', from: base + m.index, to: base + m.index + m[0].length, wrong: m[0], fix, why: r.why });
    }
  }
  // 앞에서부터, 겹치면 먼저 걸린(긴) 것만
  out.sort((a, b) => a.from - b.from || (b.to - b.from) - (a.to - a.from));
  const kept: SpellIssue[] = [];
  for (const i of out) {
    const last = kept[kept.length - 1];
    if (last && i.from < last.to) continue;
    kept.push({ ...i, id: `${i.from}-${i.wrong}` });
  }
  return kept;
}
