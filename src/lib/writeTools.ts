// 글쓰기 도구 — 로그 정리 · 맞춤법 검사
// 둘 다 「범위」를 받는다: 드래그로 고른 부분이 있으면 그 부분만, 없으면 글 전체 (호출하는 쪽이 정한다).

/* ==========================================================
   로그 정리 — 마크다운 + 앞뒤에 마크다운이 없는 문장은 ""로 감싼다
   ========================================================== */

/** 줄 앞에 오는 마크다운 — 제목 · 인용 · 목록 · 코드 · 표 · 이미지/링크 · 구분선 · 강조 시작 · HTML */
const MD_HEAD = /^(#{1,6}\s|>|[-*+]\s|\d+[.)]\s|```|~~~|\||!\[|\[[^\]]*\]\(|(-{3,}|\*{3,}|_{3,})\s*$|[*_~`]|<[a-z!/])/i;
/** 줄 끝에 오는 마크다운 — 강조·코드 닫기, 링크·이미지 닫기, 표 */
const MD_TAIL = /([*_~`]|\]\([^)]*\)|\|)$/;
/** 이미 따옴표로 감싼 문장 */
const QUOTED = /^(["“”'‘「『«].*["“”'’」』»]|["“][^"”]*)$/;
/** 「이름: 대사」 — 이름은 공백 없이 20자 이내, 앞에 [시각] 같은 머리표가 붙어도 된다 */
const SPEAKER = /^((?:\[[^\]]{1,20}\]\s*)?)([^\s:：\[\]"“]{1,20})\s*[:：]\s*(?!\/\/)(.+)$/;

/** 주소 한 줄은 그대로 — 마크다운이 자동 링크로 만든다 */
const URL_LINE = /^<?https?:\/\/\S+>?$/;
const hasMd = (t: string) => MD_HEAD.test(t) || MD_TAIL.test(t) || URL_LINE.test(t);

function tidyLine(raw: string): string {
  const line = raw.trim();
  if (!line || hasMd(line) || QUOTED.test(line)) return line;
  const sp = line.match(SPEAKER);
  if (sp) {
    const [, pre, name, said] = sp;
    const body = said.trim();
    if (hasMd(body) || QUOTED.test(body)) return `${pre}${name}: ${body}`;
    return `${pre}${name}: "${body}"`;
  }
  return `"${line}"`;
}

/**
 * 로그 한 덩어리를 정리한다.
 * · 줄마다: 앞뒤에 마크다운이 없으면 "문장" — 이미 따옴표거나 마크다운(*지문*, > 인용, # 제목 …)이면 그대로
 * · 「이름: 대사」는 대사만 감싼다
 * · 마크다운은 한 줄 바꿈을 이어 붙이므로, 줄마다 빈 줄을 하나씩 둬 각자 문단이 되게 한다
 * · 코드 블록(```) 안은 손대지 않는다
 */
export function tidyLog(text: string): string {
  const lines = text.replace(/\r\n?/g, '\n').split('\n');
  const out: string[] = [];
  let fence = false;
  let codeBuf: string[] = [];
  const push = (s: string) => { if (s) out.push(s); };
  for (const l of lines) {
    const t = l.trim();
    if (/^(```|~~~)/.test(t)) {
      if (fence) { codeBuf.push(l); push(codeBuf.join('\n')); codeBuf = []; fence = false; }
      else { fence = true; codeBuf = [l]; }
      continue;
    }
    if (fence) { codeBuf.push(l); continue; }
    // 목록·표가 이어지는 줄은 문단으로 떼지 않는다
    const prev = out[out.length - 1];
    const cont = prev !== undefined && (/^\|/.test(t) && /^\|/.test(prev.split('\n').pop() ?? '')
      || /^([-*+]\s|\d+[.)]\s)/.test(t) && /^([-*+]\s|\d+[.)]\s)/.test(prev.split('\n').pop() ?? ''));
    const tidy = tidyLine(l);
    if (!tidy) continue;
    if (cont) out[out.length - 1] = `${prev}\n${tidy}`;
    else push(tidy);
  }
  if (fence) push(codeBuf.join('\n'));   // 닫히지 않은 코드 블록은 그대로
  return out.join('\n\n');
}

/** 범위를 줄 단위로 넓힌다 — 로그 정리는 줄을 다루므로 드래그가 줄 중간에서 시작·끝나도 그 줄 전체를 */
export function expandToLines(text: string, from: number, to: number): [number, number] {
  const s = text.lastIndexOf('\n', Math.max(0, from - 1)) + 1;
  let e = text.indexOf('\n', to > from && text[to - 1] === '\n' ? to - 1 : to);
  if (e < 0) e = text.length;
  return [from === 0 ? 0 : s, e];
}

